// Writes supabase/seed.sql from js/catalogue.js: departments, groups, subcategories, provinces,
// towns, listing templates and delivery estimates. Run `node db/seed.cjs` after changing those
// settings, then apply the file (see db/README.md). Safe to apply again: rows are updated in place.
// Sellers, brands and products are not seeded; they arrive through seller sign-up.
const fs = require('node:fs');
const vm = require('node:vm');
const path = require('node:path');

const root = path.join(__dirname, '..');
const sandbox = { window: {} };
vm.runInNewContext(fs.readFileSync(path.join(root, 'js/catalogue.js'), 'utf8'), sandbox);
const D = sandbox.window.ZS_CATALOGUE;
const S = D.settings;

const q = v => v === null || v === undefined ? 'NULL'
  : v.sql ? v.sql
  : typeof v === 'boolean' || typeof v === 'number' ? String(v)
  : Array.isArray(v) ? `ARRAY[${v.map(q).join(', ')}]`
  : `'${String(v).replace(/'/g, "''")}'`;
const upsert = (table, cols, rows, key) => {
  if (!rows.length) return '';
  const set = cols.filter(c => !key.includes(c)).map(c => `${c} = EXCLUDED.${c}`).join(', ');
  return `INSERT INTO ${table} (${cols.join(', ')}) VALUES\n  ${rows.map(r => `(${r.map(q).join(', ')})`).join(',\n  ')}\n` +
    `ON CONFLICT (${key.join(', ')}) DO ${set ? 'UPDATE SET ' + set : 'NOTHING'};\n\n`;
};

// Listing-form fields to attribute_templates rows; each suggested spec name is its own row
const FIELD = { colour: 'colour', size: 'size', ageRange: 'age_range', inBox: 'components', manufacturer: 'manufacturer', condition: 'condition', features: 'features' };
const units = list => ({ sql: list.length ? `ARRAY[${list.map(q).join(', ')}]::measure_unit[]` : `'{}'::measure_unit[]` });
const templates = [];
for (const [dept, t] of Object.entries(D.attributeTemplates)) {
  let pos = 0;
  for (const f of t.fields) {
    if (f === 'specs') for (const name of t.specs || []) templates.push([dept, 'spec', name, units([]), false, pos++]);
    else if (FIELD[f]) templates.push([dept, FIELD[f], '', units(f === 'size' ? t.sizeUnits || [] : []), false, pos++]);
    else throw new Error(`Unknown template field ${f} in ${dept}`);
  }
}

let sql = `-- Generated by db/seed.cjs from js/catalogue.js. Don't edit by hand: change the catalogue and run it again.\nBEGIN;\n\n`;
sql += upsert('department_groups', ['id', 'name', 'position'], D.departmentGroups.map(([id, name], i) => [id, name, i]), ['id']);
sql += upsert('departments', ['id', 'name', 'short_name', 'group_id', 'featured', 'has_3d_art', 'position'],
  D.departments.map((d, i) => [d.id, d.name, d.short || null, d.group || null, !!d.featured, !!d.art3d, i]), ['id']);
sql += upsert('subcategories', ['department_id', 'id', 'name', 'position'],
  D.departments.flatMap(d => (d.subs || []).map(([id, name], i) => [d.id, id, name, i])), ['department_id', 'id']);
sql += upsert('provinces', ['id', 'name'], S.provinces, ['id']);
sql += upsert('towns', ['name', 'province_id', 'lat', 'lng'], S.towns, ['name']);
const est = Object.entries(S.delivery.estimates).filter(([, v]) => Array.isArray(v)).map(([zone, [min, max]]) => [zone, min, max]);
sql += est.length ? upsert('delivery_estimates', ['zone', 'min_days', 'max_days'], est, ['zone'])
  : '-- Delivery estimates: none set in settings.delivery.estimates yet\n\n';
// Templates are replaced whole, so fields removed from the catalogue go too
sql += 'DELETE FROM attribute_templates;\n';
sql += upsert('attribute_templates', ['department_id', 'attribute', 'spec_key', 'size_units', 'required', 'position'], templates,
  ['department_id', 'attribute', 'spec_key']);
sql += 'COMMIT;\n';

fs.writeFileSync(path.join(root, 'supabase/seed.sql'), sql);
console.log(`supabase/seed.sql: ${D.departmentGroups.length} groups, ${D.departments.length} departments, ` +
  `${D.departments.reduce((n, d) => n + (d.subs || []).length, 0)} subcategories, ${S.provinces.length} provinces, ` +
  `${S.towns.length} towns, ${templates.length} template rows, ${est.length} delivery estimates`);
